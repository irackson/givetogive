import 'server-only';
import { createHmac } from 'node:crypto';
import { createMailgunDelivery } from './mailgun.ts';
import { isRenderedMessage, renderMessage } from './templates.ts';
import { identity, MailPolicyError } from './policy.ts';
import { getGiveToGiveMailRuntime, type GiveToGiveMailRuntime } from './runtime.ts';
import type { PayloadBinder, TransportConfig } from './types.ts';

export type GiveAuthMail = {
	readonly to: string;
	readonly url: string;
	readonly purpose: 'email_verification' | 'password_reset';
	/** Assigned/preserved by an admitted upstream durable intent, never generated by this sender. */
	readonly intentKey: string;
};
export type GiveCampaign = {
	readonly intentKey: string;
	readonly to: string;
	readonly title: string;
	readonly body: string;
	readonly actionURL: string;
	readonly subscription: { readonly scope: 'app-updates'; readonly unsubscribeURL: string };
};

/** Explicit server configuration only; no provider/default/key loading in the transport. */
export function readGiveMailConfiguration(source: Readonly<Record<string, string | undefined>>): TransportConfig {
	const profile = identity('givetogive');
	if (source['EMAIL_PROVIDER'] !== 'mailgun' || source['MAILGUN_DOMAIN'] !== 'ianrackson.com'
		|| source['MAILGUN_REGION'] !== 'us' || source['EMAIL_FROM'] !== profile.from
		|| source['EMAIL_REPLY_TO'] !== profile.replyTo || source['EMAIL_CONTACT'] !== profile.replyTo) {
		throw new MailPolicyError('invalid_give_mail_configuration');
	}
	const apiKey = source['MAILGUN_API_KEY'];
	if (!apiKey || apiKey.length > 256 || /[\s:]/.test(apiKey)) throw new MailPolicyError('invalid_give_mail_configuration');
	return Object.freeze({ apiKey, domain: 'ianrackson.com', region: 'us' });
}

/** Host-injected private material only; public fixtures occur exclusively in tests. */
export function createGiveMailBinding(material: Uint8Array): PayloadBinder {
	if (!(material instanceof Uint8Array) || material.byteLength < 32 || material.byteLength > 256) {
		throw new MailPolicyError('private_binding_unavailable');
	}
	const key = Buffer.from(material);
	return async (message, scope) => {
		if (scope !== 'mailgun:us:ianrackson.com' || !isRenderedMessage(message) || message.app !== 'givetogive'
			|| !['email-verification', 'password-reset', 'campaign'].includes(message.kind)) {
			throw new MailPolicyError('invalid_give_mail_preparation');
		}
		return createHmac('sha256', key).update('give-mail-payload:v1\0').update(scope).update('\0')
			.update(JSON.stringify(message)).digest('hex');
	};
}

export function createGiveToGiveMailer(runtime: GiveToGiveMailRuntime) {
	if (runtime.config.region !== 'us' || runtime.config.domain !== 'ianrackson.com') {
		throw new MailPolicyError('invalid_give_mail_configuration');
	}
	const deliver = createMailgunDelivery(runtime.config, runtime);
	return Object.freeze({
		sendAuth(input: GiveAuthMail) {
			if (!['email_verification', 'password_reset'].includes(input.purpose)) throw new MailPolicyError('invalid_kind');
			return deliver(input.intentKey, renderMessage({ app: 'givetogive', to: input.to,
				kind: input.purpose === 'email_verification' ? 'email-verification' : 'password-reset', actionURL: input.url }));
		},
		/** Preparation only: no campaign route, scheduler, subscription or consent admission is added. */
		sendCampaign(input: GiveCampaign) {
			if (input.subscription?.scope !== 'app-updates') throw new MailPolicyError('invalid_subscription');
			return deliver(input.intentKey, renderMessage({ app: 'givetogive', kind: 'campaign', to: input.to,
				title: input.title, body: input.body, actionURL: input.actionURL, subscription: input.subscription }));
		},
	});
}

/** Preserve uncertain outcomes; no fallback, automatic intent creation, logging or resend. */
export async function sendGiveAuthMail(input: Omit<GiveAuthMail, 'intentKey'> & { readonly intentKey?: string }) {
	const runtime = getGiveToGiveMailRuntime();
	if (!runtime || !input.intentKey) return { delivered: false, retryAllowed: false } as const;
	try {
		const outcome = await createGiveToGiveMailer(runtime).sendAuth({ ...input, intentKey: input.intentKey });
		// Known queue acceptance remains known even if receipt acknowledgement was lost.
		// Provider IDs and storage diagnostics never cross the public auth result boundary.
		return { delivered: outcome.state === 'accepted', retryAllowed: false } as const;
	} catch {
		return { delivered: false, retryAllowed: false } as const;
	}
}
